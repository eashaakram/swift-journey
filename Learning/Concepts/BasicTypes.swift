import Foundation

// String is "regular text"
let myFirstItem: String = "Hello, world!"

// Refrence previously created objects
let myTitle = myFirstItem

// Boolean (aka Bool) is true or false
let mySecondItem: Bool = true
let myThirdItem: Bool = false

// Do not do!
// let myFourthItem: String = "true"  This is not Bool

// Swift is type-safe language
let myFifthItem: Bool = true
let mySixthItem: String = "Hello, world!"
let mySeventhItem = true

// Date
let myFirstDate: Date = Date()
print("First: \(myFirstDate)")
// More easier
let mySecondDate: Date = .now
print("Second: \(mySecondDate)")

// Number can be Int, Double, CGFloat & more

let myFirstNumber: Int = 1 // Int is whole number
let mySecondNumber: Double = 1.0
let myThirdNumber: Float = 1.0

// CGFloat for UI


